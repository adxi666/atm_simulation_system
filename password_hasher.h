#ifndef ATM_PASSWORD_HASHER_H
#define ATM_PASSWORD_HASHER_H

#include <string>

/*
 * ============================================================================
 * 用户账号密码（PIN）的加密存储方案 —— bcrypt
 * ============================================================================
 *
 * 一、目标与威胁模型
 *   账号（Account.id）与密码（Account.pinHash）最终都会落到本地 SQLite 文件
 *   atm.db。数据库文件一旦被复制（U 盘拷贝、备份泄露、同步盘、木马外传等），
 *   攻击者最直接的获利就是“拿到所有人的明文密码”。因此本程序遵循一条硬性
 *   原则：明文密码只在内存里存在一瞬间（用户输入 → 校验），任何持久化介质
 *   上都不得出现明文密码。
 *
 *   之所以选择“不可逆哈希”而不是“可逆加密”：本程序只需要判断“用户输入的
 *   密码是否正确”，永远不需要把密码还原成明文，所以不保存任何可以还原明文
 *   的密钥。这样即使数据库文件加上程序本体一起泄露，攻击者也拿不到明文密码。
 *
 * 二、为什么是 bcrypt，而不是 MD5 / SHA-256 之类的快速哈希
 *   1. 加盐（salt）：bcrypt 每次散列都使用 16 字节（128 位）密码学随机盐，
 *      盐随哈希一起保存。同一密码在不同账户、不同时间得到的哈希完全不同，
 *      攻击者无法用“彩虹表（rainbow table）”或“预计算字典”批量反查，也无法
 *      通过“哈希相同”推断出哪两个账户用了同一密码。
 *   2. 工作因子（cost）：bcrypt 内部是“可自动加盐的 Blowfish（Eksblowfish）”，
 *      cost 参数表示昂贵密钥扩展次数的以 2 为底的对数。本项目取 cost = 10，即做
 *      2^10 = 1024 轮密钥扩展。单次校验在普通 PC 上约 50～100 毫秒，用户
 *      几乎无感；但攻击者暴力尝试的总成本会随之提高约 1024 倍。
 *   3. 抗硬件加速：bcrypt 对内存的访问依赖 4 KB 的 S 盒，GPU / ASIC 难以像
 *      对付 MD5（且 MD5 已被证明可构造碰撞）那样获得巨大的并行加速比。
 *   4. 公认标准：bcrypt 是 OpenBSD 引入、至今仍被 PHP password_hash、Python
 *      bcrypt、Node bcryptjs 等主流库采用的密码存储格式，有公开规范与大量
 *      实现互相验证，避免“自制加密算法”带来的风险。
 *
 * 三、存储格式（BCrypt Password Hash Format）
 *   数据库中 accounts.pin 列保存的是形如下面 60 个字符的字符串：
 *
 *       $2b$10$N9qo8uLOickgx2ZMRZoMyeIjZAgcfl7p92ldGxad68LJZdL17lhWy
 *       └┬┘└┬┘└─────────┬──────────┘└─────────────┬──────────────┘
 *        │  │           │                          │
 *        │  │           │                          └─ 哈希值（31 字符，编码自 23 字节密文）
 *        │  │           └─ 盐（22 字符，编码自 16 字节随机数）
 *        │  └─ cost = 10（2^10 = 1024 轮，固定两位十进制数）
 *        └─ 版本号：$2b$ 为当前修订版（修复了早期 $2a$ 对超长密码/空字节的
 *           已知缺陷）
 *
 *   盐与哈希都使用 bcrypt 自定义的 base64 表（字母表为
 *   "./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"），
 *   因此数据库里看到的是带 . 和 / 的字符串，而不是普通 base64。
 *
 * 四、校验流程（“加盐哈希”如何判断密码是否正确）
 *      用户输入密码 ──┐
 *                     ▼
 *      从数据库读出该账户的哈希 → 解析出 cost 与 16 字节盐
 *                     ▼
 *      用“同一份盐 + 用户输入”重新跑一次 bcrypt → 得到新哈希
 *                     ▼
 *      新哈希 == 数据库中的完整哈希 ？ ── 是 → 密码正确
 *                                      └─ 否 → 密码错误（不泄露任何细节）
 *
 *   注意：bcrypt 哈希是“加盐的”，同一密码每次生成的哈希都不同，所以校验时
 *   不能直接比较算出来的“裸哈希”，而是必须拿数据库里保存的盐重新计算，再
 *   比较完整的字符串（本实现用 constant-time 比较，避免计时侧信道）。
 *
 * 五、明文密码从不会落盘的三个关口
 *   1. 新开户、修改密码、找回密码：先对明文密码做 bcrypt 散列，把结果写进
 *      Account::pinHash，再写入数据库。
 *   2. 打开旧数据库后的加载阶段：如果发现历史遗留的明文密码，会立即用 bcrypt
 *      重新散列；随后任何一次写库都会把旧明文覆盖成哈希，实现平滑迁移。
 *   3. 保存阶段（最后一道保险）：写库前再次检查所有账户，一旦发现仍不是 bcrypt
 *      格式的密码就当场散列；散列失败则拒绝写库，从机制上保证“明文密码永远
 *      进不了数据库”。
 *
 * 六、其他安全约定
 *   - 盐由操作系统密码学随机数（Windows BCryptGenRandom）生成，不使用
 *     rand()/time() 之类的弱随机源。
 *   - 密码长度超过 72 字节时 bcrypt 只使用前 72 字节（算法固有限制），
 *     本项目密码固定为 6 位数字，远小于上限。
 *   - 校验成功后才把哈希写回内存缓存，失败时不做任何区分（“账户不存在”与
 *     “密码错误”在业务层分别提示，但不暴露哈希细节）。
 *   - 数据库本身仍是明文文件（SQLite，未开 SQLCipher），本方案解决的是
 *     “账号密码不能以明文落盘”的问题；防止整库被篡改可另行考虑文件权限、
 *     SQLCipher 或操作系统级磁盘加密。
 * ============================================================================
 */

namespace bcrypt {

// 一次性完成：生成随机盐 → 计算哈希 → 返回 "$2b$<cost>$<salt><hash>"。
// 失败（随机数不可用等）时返回空字符串。
std::string hashPassword(const std::string& password);

// 用给定的完整 bcrypt 哈希校验明文密码。哈希损坏、cost 非法时返回 false。
bool verifyPassword(const std::string& password, const std::string& bcryptHash);

// 判断字符串是否已经是合法的 bcrypt 哈希（用于识别/迁移旧明文密码）。
bool isBcryptHash(const std::string& value);

// 用指定的 cost（如 10）与固定盐生成哈希，供自测/导入工具使用；
// salt 形如 "$2b$10$abcdefghijklmnopqrstuu"。生产流程请用 hashPassword()。
std::string hashPasswordWithSalt(const std::string& password, const std::string& salt);

}  // namespace bcrypt

#endif
